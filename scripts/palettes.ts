/* ------------------------------------------------------------------------ *
 * Expressive palettes.
 *
 * These take their cue from animation colour scripts rather than from product
 * design. That is a real difference in kind, not just in loudness: a frame of
 * animation has no body text to keep readable, so its palette is free to run
 * at a chroma no interface can survive.
 *
 * So each one below keeps the *grade* — chroma range, value range, what the
 * shadows are made of, which two hues fight — and spends it where an interface
 * can afford it. The loud colours land on `primary`, `accent`, `ring` and the
 * state roles; `background`, `muted` and `border` stay disciplined, because a
 * saturated surface makes an app unusable no matter how good it looks in a
 * screenshot.
 *
 * Two recurring tricks, both already used by the core palettes:
 *
 *   A colour too light for white text becomes a fill with DARK text instead
 *   (`primary-foreground` is not always white — see Roast).
 *
 *   A colour that collides with a state role gets traded for it rather than
 *   fought: Cathode's phosphor green is not the primary, it IS `success`.
 * ------------------------------------------------------------------------ */

