/**
 * Palette source of truth.
 *
 * Build-time only — this file is never published. `scripts/build-themes.ts`
 * reads it and generates two stylesheets per palette into `src/themes/`, which
 * holds nothing but generated CSS and is copied wholesale to `dist/themes/`:
 *
 *   <name>.css          `:root` + `.dark` — the plain import, for apps that
 *                       ship one palette. No attribute on `<html>` required.
 *   <name>.scoped.css   `[data-palette="<name>"]` — for apps that let their
 *                       own users switch palettes at runtime via ThemeProvider.
 *
 * The generated files are committed so the published output is reviewable in
 * diffs and so publint can validate the `./themes/*` exports at build time.
 * Edit this file, never the generated CSS.
 *
 * Every palette must define the full token set — the scoped stylesheets are
 * applied on top of an arbitrary other palette, so a missing token would leak
 * the previous palette's value rather than falling back to the neutral base.
 */

